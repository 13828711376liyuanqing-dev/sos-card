"""SAM | 2026-10-23 +08:00 | Generate/verify YP001 project headers using SDK-compatible PSS; never authorize installation or change firmware versions."""
import argparse
import base64
import hashlib
import json
from pathlib import Path
import re
import struct
import xml.etree.ElementTree as ET
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.asymmetric import padding, rsa
from gr_native_inspect import inspect_image, read_bounded, require, SLOT_BYTES, TRAILER_BYTES


def digest_bytes(value):
    require(isinstance(value, str) and re.fullmatch('[0-9a-f]{64}', value) is not None,
            'PROJECT_CONTRACT_PIN_REQUIRED')
    require(value != '0'*64, 'PROJECT_CONTRACT_PIN_REQUIRED')
    return bytes.fromhex(value)


def identity(payload):
    require(isinstance(payload, bytes) and 8 <= len(payload) <= SLOT_BYTES-TRAILER_BYTES,
            'PROJECT_PAYLOAD_SIZE')
    msp, reset = struct.unpack_from('<II', payload)
    require(0x20006000 < msp <= 0x20040000 and msp % 8 == 0 and reset & 1 and
            0x00202008 <= (reset & ~1) < 0x00202000+len(payload), 'PROJECT_VECTORS')
    marks = re.findall(rb'YP001_FW\|GR5526\|(\d{3})\.(\d{3})\.(\d{3})\|(\d{1,5})\|END', payload)
    require(len(marks) == 1, 'PROJECT_IDENTITY')
    major, minor, patch, build = map(int, marks[0])
    require(1 <= build <= 65535, 'PROJECT_BUILD')
    return f'{major}.{minor}.{patch}', major*1000000+minor*1000+patch, build


def verify_image(image, public_xml, trusted_xml_sha256, layout_sha256, data_sha256):
    # The native inspector authenticates every byte before project fields are used.
    result = inspect_image(image, public_xml, trusted_xml_sha256)
    payload, tail = image[:-TRAILER_BYTES], image[-TRAILER_BYTES:]
    version, number, build = identity(payload)
    expected = struct.pack('<4s7I', b'YPGR', len(payload), 1, 0x00202000, 5526, number, build, 1)
    require(tail[:32] == expected, 'PROJECT_HEADER')
    require(tail[32:64] == digest_bytes(layout_sha256), 'PROJECT_LAYOUT')
    require(tail[64:96] == hashlib.sha256(payload).digest(), 'PROJECT_PAYLOAD_HASH')
    require(tail[96:128] == digest_bytes(data_sha256), 'PROJECT_DATA_CONTRACT')
    # Project bytes have their own names; do not present them as vendor fw_info fields.
    result.pop('observed_header_words', None)
    result.update(schema='YP001_GR_PROJECT_PSS_V1', header_semantics='PROJECT_V1_VERIFIED',
                  version=version, version_number=number, build=build, board='GR5526', profile_version=1,
                  layout_sha256=layout_sha256, data_contract_sha256=data_sha256,
                  payload_sha256=hashlib.sha256(payload).hexdigest(),
                  device_installable=False,
                  remaining_gates=['contract_approval_and_data_inventory', 'hardware_pkc',
                                   'project_boot_deployment', 'device_ota'])
    return result


def sign_image(payload, private_key, public_xml, trusted_xml_sha256,
               layout_sha256, data_sha256, target_version):
    version, number, build = identity(payload)
    require(target_version == version, 'PROJECT_TARGET_MISMATCH')
    layout, data = digest_bytes(layout_sha256), digest_bytes(data_sha256)
    require(isinstance(private_key, rsa.RSAPrivateKey) and private_key.key_size == 2048, 'PROJECT_PRIVATE_KEY')
    p = private_key.public_key().public_numbers()
    require(p.e == 65537, 'PROJECT_PRIVATE_KEY')
    header = struct.pack('<4s7I', b'YPGR', len(payload), 1, 0x00202000, 5526, number, build, 1)
    header += layout + hashlib.sha256(payload).digest() + data
    blob = (p.n.to_bytes(256, 'little') + struct.pack('<I', p.e) +
            pow(2, 4096, p.n).to_bytes(256, 'little') +
            struct.pack('<I', (-pow(p.n, -1, 1 << 32)) & 0xffffffff))
    span = payload + header + blob
    signature = private_key.sign(span, padding.PSS(mgf=padding.MGF1(hashes.SHA256()), salt_length=32), hashes.SHA256())[::-1]
    image = span + signature
    # Refuse output if key pin, generated bytes, capacity or contract do not verify.
    verify_image(image, public_xml, trusted_xml_sha256, layout_sha256, data_sha256)
    return image


def load_private(path):
    # Never print XML, private parameters or provider exception details.
    try:
        root = ET.fromstring(read_bounded(path, 16384))
        names = ['Modulus', 'Exponent', 'P', 'Q', 'DP', 'DQ', 'InverseQ', 'D']
        require(root.tag == 'RSAKeyValue' and len(root) == 8 and
                sorted(n.tag for n in root) == sorted(names), 'PRIVATE_XML')
        values = {name: int.from_bytes(base64.b64decode(root.findtext(name), validate=True), 'big') for name in names}
        return rsa.RSAPrivateNumbers(values['P'], values['Q'], values['D'], values['DP'],
            values['DQ'], values['InverseQ'], rsa.RSAPublicNumbers(values['Exponent'], values['Modulus'])).private_key()
    except Exception as exc:
        raise ValueError('PROJECT_PRIVATE_KEY_INVALID') from None


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--payload', required=True)
    parser.add_argument('--private-key', required=True)
    parser.add_argument('--public-key', required=True)
    parser.add_argument('--trusted-xml-sha256', required=True)
    parser.add_argument('--layout-sha256', required=True)
    parser.add_argument('--data-contract-sha256', required=True)
    parser.add_argument('--target-version', required=True)
    parser.add_argument('--output', required=True, help='New candidate filename; never overwrites existing files')
    args = parser.parse_args()
    try:
        payload = read_bounded(args.payload, SLOT_BYTES-TRAILER_BYTES)
        public = read_bounded(args.public_key, 16384)
        image = sign_image(payload, load_private(args.private_key), public, args.trusted_xml_sha256,
                           args.layout_sha256, args.data_contract_sha256, args.target_version)
        report = verify_image(image, public, args.trusted_xml_sha256, args.layout_sha256, args.data_contract_sha256)
        with Path(args.output).open('xb') as out:
            out.write(image)
        # Diagnostic JSON on stdout contains no private key material. Output is a candidate.
        print(json.dumps(report, indent=2))
        return 0
    except Exception:
        print(json.dumps({'device_installable': False, 'error': 'PROJECT_SIGN_OR_OUTPUT_FAILED'}))
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
