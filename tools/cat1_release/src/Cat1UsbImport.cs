// SAM | 2026-10-30 10:21 +08:00 | Standalone CAT1 (Air780EGH) USB_IMPORT builder/checker. Runs on any Windows 10/11 PC with the
// built-in .NET Framework 4.x; luac_64bit.exe ships in the same folder (sha256 pinned below). Same rules as usb_import_tool.py:
//   every <name>.lua except main.lua -> <name>.luac (luac -s); libfota2.lua left out while nothing references it;
//   main.lua stays source with a never-executed `if false then require(...) end` anchor block in front, listing every
//   packaged module main.lua does not require directly (so the Luatools merge packs indirectly loaded modules);
//   vendor_luac/*.luac (pinned in vendor.json) and *.mp3 are copied.
// Checks: compile, UTF-8, flat names <= 23 bytes, main.lua identity/OTA fields, require targets, vendor hashes,
// LuaDB size <= 524288, written files re-read against the staged ones, integrity.json.
// Window: no arguments.  CLI: Cat1UsbImport.exe --source <dir> --out <dir> [--vendor <dir>] [--check-only] [--force]
