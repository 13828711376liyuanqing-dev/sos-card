        public MainWindow(string defaultSource)
        {
            // SAM | 2026-10-30 11:40 +08:00 | Only what must be chosen: source folder and output place. Vendor libraries come from the tool folder; the Luatools
            // folder is asked only when "检查依赖版本" is pressed; an existing USB_IMPORT is replaced only after a confirmation.
            Text = "CAT1 USB_IMPORT 生成与检查 v" + Builder.Version; Width = 1010; Height = 560; Font = new Font("Microsoft YaHei UI", 9);
