            bool checkOnly = false, force = false, deps = false;
            for (int i = 0; i < args.Length; i++)
            {
                switch (args[i])
                {
                    case "--version": Console.WriteLine("Cat1UsbImport v" + Builder.Version + "｜" + Deps.Banner(Builder.ToolDir)); return 0;
                    case "--deps": deps = true; break;
                    case "--luatools": luatools = args[++i]; break;
                    case "--source": source = args[++i]; break;
                    case "--vendor": vendor = args[++i]; break;
                    case "--out": outDir = args[++i]; break;
                    case "--check-only": checkOnly = true; break;
                    case "--package-source": Builder.PackageSource = true; break;
                    case "--force": force = true; break;
                    default:
                        Console.WriteLine("用法：Cat1UsbImport.exe --source <源码目录> --out <输出位置> [--vendor <厂商库目录>] [--check-only] [--force]\r\n      Cat1UsbImport.exe --deps [--luatools <已安装的Luatools目录>]   检查依赖版本\r\n      Cat1UsbImport.exe --version");
