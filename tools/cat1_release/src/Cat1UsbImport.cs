            string defaultSource = File.Exists(Path.Combine(guess, "main.lua")) ? guess : "";
            if (args.Length == 0)
            {
                FreeConsole(); // console build (for the CLI); the window mode does not need it
                Application.EnableVisualStyles();
                Application.Run(new MainWindow(defaultSource));
                return 0;
            }
            // SAM | 2026-10-30 11:16 +08:00 | Hidden: render the window to a PNG (layout checks without clicking).
            if (args.Length == 2 && args[0] == "--snapshot") { FreeConsole(); Application.EnableVisualStyles(); using (var f = new MainWindow(defaultSource)) { f.Show(); Application.DoEvents();
                using (var bmp = new System.Drawing.Bitmap(f.Width, f.Height)) { f.DrawToBitmap(bmp, new System.Drawing.Rectangle(0, 0, f.Width, f.Height)); bmp.Save(args[1], System.Drawing.Imaging.ImageFormat.Png); } } return 0; }
            Console.OutputEncoding = Encoding.UTF8;
