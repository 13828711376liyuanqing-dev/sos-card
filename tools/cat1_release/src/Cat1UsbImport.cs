    class Report
    {
        public readonly List<string> Errors = new List<string>(), Warnings = new List<string>();
        readonly Action<string> log;
        public Report(Action<string> log) { this.log = log; }
        public void Log(string s) { log(s); }
        public void Ok(string s) { log("  OK    " + s); }
        public void Warn(string s) { Warnings.Add(s); log("  WARN  " + s); }
        public void Error(string s) { Errors.Add(s); log("  ERROR " + s); }
        public string Summary() { return "结果：" + (Errors.Count > 0 ? "失败" : "通过") + "（错误 " + Errors.Count + "，警告 " + Warnings.Count + "）"; }
    }

    static class Builder
    {
        public const string Version = "1.4";
        public const int Capacity = 0x80000, NameLimit = 23;
        // SAM | 2026-10-30 11:04 +08:00 | Vendor libraries next to the exe (toolkit folder) win over <source>/vendor_luac.
        public static string VendorFor(string source) { string local = Path.Combine(ToolDir, "vendor_luac"); return Directory.Exists(local) ? local : Path.Combine(source, "vendor_luac"); }
        const string LuacName = "luac_64bit.exe";
        const string LuacSha256 = "e4180102b388a09153c416ca2aa80dd90df257a10efe8abbbd5bcc5285ab0957";
        const string AnchorHead = "-- Packaging dependency inventory only (generated by Cat1UsbImport.exe); never executed.";
        static readonly string[] ExcludedUnlessUsed = { "libfota2" };
        static readonly string[] AssetSuffixes = { ".mp3" };
        static readonly HashSet<string> FirmwareModules = new HashSet<string> { "sys", "sysplus", "json", "crypto", "zbuff", "pack", "string", "io", "os", "table", "math" };
        static readonly UTF8Encoding Utf8Strict = new UTF8Encoding(false, true), Utf8 = new UTF8Encoding(false);

        public static string ToolDir { get { return AppDomain.CurrentDomain.BaseDirectory; } }
        static string Luac { get { return Path.Combine(ToolDir, LuacName); } }

        public static string Sha256(byte[] b)
        {
            using (var h = SHA256.Create()) return BitConverter.ToString(h.ComputeHash(b)).Replace("-", "").ToLowerInvariant();
        }

        static bool Compile(string src, string dst, out string message)
        {
            var psi = new ProcessStartInfo(Luac, "-s -o \"" + dst + "\" \"" + src + "\"")
            { UseShellExecute = false, RedirectStandardError = true, RedirectStandardOutput = true, CreateNoWindow = true };
            using (var p = Process.Start(psi))
            {
                string err = p.StandardError.ReadToEnd() + p.StandardOutput.ReadToEnd();
                p.WaitForExit();
                message = err.Trim();
                return p.ExitCode == 0 && File.Exists(dst);
            }
        }

        static string StripComments(string t)
        {
            t = Regex.Replace(t, @"--\[(=*)\[.*?\]\1\]", "", RegexOptions.Singleline);
            return Regex.Replace(t, @"--[^\n]*", "");
        }

        static HashSet<string> Requires(string text)
        {
            var set = new HashSet<string>();
            foreach (Match m in Regex.Matches(StripComments(text), @"require\s*\(?\s*[""']([A-Za-z0-9_.]+)[""']")) set.Add(m.Groups[1].Value);
            return set;
        }

        static string Field(string main, string key)
        {
            var m = Regex.Match(main, "^" + key + @"\s*=\s*[""']?([^""'\r\n]+)", RegexOptions.Multiline);
            return m.Success ? m.Groups[1].Value.Trim() : null;
        }

        public static long LuaDbSize(Dictionary<string, long> files)
        {
            long total = 24 + 18 + Encoding.ASCII.GetByteCount(".airm2m_all_crc#.bin") + 16;
            foreach (var kv in files) total += 18 + Utf8.GetByteCount(kv.Key) + kv.Value;
            return total;
        }

        // SAM | 2026-10-30 16:27 +08:00 | --package-source: the source is the TARGET version that goes into an upgrade package (PRODUCT_VERSION == OTA_TRIAL_TARGET), not a receiver to flash.
        public static bool PackageSource;
        public static List<string> Build(string source, string vendor, string outDir, bool checkOnly, bool force, Report rep)
        {
            rep.Log("Cat1UsbImport v" + Version + "｜" + Deps.Banner(ToolDir));
            rep.Log("源码：" + source + "\r\n厂商库：" + vendor);
            rep.Log("[1] 输入检查");
            if (!File.Exists(Luac)) { rep.Error("找不到 " + LuacName + "（应与本程序在同一文件夹）：" + Luac); return null; }
            if (Sha256(File.ReadAllBytes(Luac)) != LuacSha256) { rep.Error(LuacName + " 的 sha256 不是已验证的版本"); return null; }
            if (!File.Exists(Path.Combine(source, "main.lua"))) { rep.Error("源码目录里没有 main.lua：" + source); return null; }
            var texts = new SortedDictionary<string, string>(StringComparer.Ordinal);
            foreach (var p in Directory.GetFiles(source, "*.lua").OrderBy(x => x, StringComparer.Ordinal))
            {
                byte[] raw = File.ReadAllBytes(p);
                string text;
                try { text = Utf8Strict.GetString(raw); } catch (DecoderFallbackException) { rep.Error(Path.GetFileName(p) + " 不是 UTF-8"); continue; }
                if (text.Length > 0 && text[0] == '﻿') text = text.Substring(1);
                if (!text.Contains("\r\n") && text.Contains("\n")) rep.Warn(Path.GetFileName(p) + " 是 LF 换行（本项目源码约定 CRLF）");
                texts[Path.GetFileNameWithoutExtension(p)] = text;
            }
            string main = texts.ContainsKey("main") ? texts["main"] : "";
            texts.Remove("main");
            var used = new HashSet<string>(Requires(main));
            foreach (var t in texts.Values) used.UnionWith(Requires(t));
            var modules = new List<string>();
            foreach (var kv in texts)
            {
                string name = kv.Key;
                if (ExcludedUnlessUsed.Contains(name) && !used.Contains(name) &&
                    !texts.Any(o => o.Key != name && StripComments(o.Value).Contains(name)))
                { rep.Ok(name + ".lua 未被任何文件引用，按规则不打包"); continue; }
                modules.Add(name);
            }
            var assets = Directory.GetFiles(source).Where(f => AssetSuffixes.Contains(Path.GetExtension(f).ToLowerInvariant()))
                .OrderBy(x => x, StringComparer.Ordinal).ToList();

            rep.Log("[2] 厂商预编译库");
            var vendorFiles = new List<string>();
            string manifest = Path.Combine(vendor, "vendor.json");
            if (!File.Exists(manifest)) rep.Error("缺少 " + manifest);
            else
            {
                var doc = (Dictionary<string, object>)new JavaScriptSerializer().DeserializeObject(File.ReadAllText(manifest, Utf8));
                var pinned = ((Dictionary<string, object>)doc["files"]).ToDictionary(k => k.Key, k => (string)k.Value);
                foreach (var kv in pinned.OrderBy(k => k.Key, StringComparer.Ordinal))
                {
                    string p = Path.Combine(vendor, kv.Key);
                    if (!File.Exists(p)) rep.Error("缺少厂商库 " + kv.Key);
                    else if (Sha256(File.ReadAllBytes(p)) != kv.Value) rep.Error("厂商库 " + kv.Key + " 的 sha256 与 vendor.json 不一致");
                    else vendorFiles.Add(p);
                }
                var extra = Directory.GetFiles(vendor, "*.luac").Select(Path.GetFileName).Where(n => !pinned.ContainsKey(n)).ToList();
                if (extra.Count > 0) rep.Warn("vendor 目录里有未登记的文件（不会打包）：" + string.Join(", ", extra));
                if (vendorFiles.Count == pinned.Count) rep.Ok(vendorFiles.Count + " 个厂商库 sha256 一致");
                var clash = vendorFiles.Select(Path.GetFileNameWithoutExtension).Intersect(modules).ToList();
                if (clash.Count > 0) rep.Error("源码和厂商库同名：" + string.Join(", ", clash));
            }

            rep.Log("[3] 文件名与依赖");
            var names = modules.Select(m => m + ".luac").Concat(vendorFiles.Select(Path.GetFileName)).Concat(assets.Select(Path.GetFileName)).Concat(new[] { "main.lua" }).ToList();
            var longNames = names.Where(n => Utf8.GetByteCount(n) > NameLimit).ToList();
            if (longNames.Count > 0) rep.Error("文件名超过 23 字节（Luatools 限制）：" + string.Join(", ", longNames));
            else rep.Ok(names.Count + " 个文件名都 <= 23 字节");
            var available = new HashSet<string>(modules.Concat(vendorFiles.Select(Path.GetFileNameWithoutExtension))) { "main" };
            var missing = used.Where(m => !available.Contains(m) && !FirmwareModules.Contains(m) && !ExcludedUnlessUsed.Contains(m)).OrderBy(x => x).ToList();
            if (missing.Count > 0) rep.Warn("源码里 require 了这些模块，但输出中没有（若属于固件内置库可忽略）：" + string.Join(", ", missing));
            else rep.Ok("所有字面量 require 都能找到对应模块");

            rep.Log("[4] main.lua 版本与 OTA 设置");
            var fields = new Dictionary<string, string>();
            foreach (var k in new[] { "VERSION", "PRODUCT_VERSION", "FW_RELEASE_BUILD", "OTA_TRIAL_MD5", "OTA_TRIAL_SOURCE", "OTA_TRIAL_TARGET" }) fields[k] = Field(main, k);
            foreach (var k in new[] { "VERSION", "PRODUCT_VERSION", "FW_RELEASE_BUILD" }) if (fields[k] == null) rep.Error("main.lua 缺少 " + k);
            rep.Ok("VERSION=" + fields["VERSION"] + " PRODUCT_VERSION=" + fields["PRODUCT_VERSION"] + " BUILD=" + fields["FW_RELEASE_BUILD"]);
            string md5 = fields["OTA_TRIAL_MD5"];
            if (md5 != null)
            {
                if (!Regex.IsMatch(md5, "^[0-9a-f]{32}$")) rep.Error("OTA_TRIAL_MD5 不是 32 位小写十六进制：" + md5);
                else if (md5.All(c => c == '0')) { if (!PackageSource) rep.Warn("OTA_TRIAL_MD5 为全零：这套脚本不能发起 OTA（打好升级包后再冻结）"); }
                else rep.Ok("OTA_TRIAL_MD5=" + md5);
                if (PackageSource)
                {
                    if (fields["OTA_TRIAL_TARGET"] != fields["PRODUCT_VERSION"]) rep.Error("升级包源码的 PRODUCT_VERSION=" + fields["PRODUCT_VERSION"] + " 必须等于 OTA_TRIAL_TARGET=" + fields["OTA_TRIAL_TARGET"]);
                    else rep.Ok("升级包源码：目标版本 " + fields["OTA_TRIAL_TARGET"] + "（范围 " + fields["OTA_TRIAL_SOURCE"] + " -> " + fields["OTA_TRIAL_TARGET"] + "）");
                }
                else if (fields["OTA_TRIAL_SOURCE"] != fields["PRODUCT_VERSION"])
                {
                    // SAM | 2026-11-08 +08:00 | Zero MD5 = this script set cannot start an OTA (OTA_TRIAL is refused before any action), so a range
                    // that differs from the version is harmless for self-test imports. A frozen MD5 (a real OTA receiver) keeps the hard error.
                    string msg = "OTA_TRIAL_SOURCE=" + fields["OTA_TRIAL_SOURCE"] + " 与 PRODUCT_VERSION=" + fields["PRODUCT_VERSION"] + " 不一致";
                    if (md5.All(c => c == '0')) rep.Warn(msg + "：OTA_TRIAL_MD5 为全零，这套脚本不能发起 OTA，范围不影响自用测试；这是旧固件的写法，新版设备代码已经不用 OTA_TRIAL_*（OTA 出厂即可接收，不再需要接收端）");
                    else rep.Error(msg + "（接收端版本必须等于设备当前版本）");
                }
                else rep.Ok("OTA 范围 " + fields["OTA_TRIAL_SOURCE"] + " -> " + fields["OTA_TRIAL_TARGET"]);
            }
            if (rep.Errors.Count > 0) return null;

            // SAM | 2026-11-04 +08:00 | Mandatory OTA behaviours (user rule; same list as tools/ota_oneclick MUST_HAVE): before an OTA
            // the device deletes its app logs and reports it, writes no log files during the OTA, and keeps CAT1 powered via GR.
            rep.Log("[4b] OTA 必检功能（清日志、保电）");
            string upd = Path.Combine(source, "update.lua"), fsl = Path.Combine(source, "fs_log.lua");
            if (!File.Exists(upd)) rep.Warn("没有 update.lua：这套脚本不含 OTA，不能用来做整机升级");
            else
            {
                string u = File.ReadAllText(upd), f = File.Exists(fsl) ? File.ReadAllText(fsl) : "";
                var must = new[] {
                    new[] { u, "'/log/app.log', '/log/app.log.bak'", "update.lua：OTA 发令前删除 app 日志（app.log 和 .bak）" },
                    new[] { u, "[OTA] LOG_CLEARED", "update.lua：删日志后回报 [OTA] LOG_CLEARED" },
                    new[] { u, "for _, name in ipairs({'accept', 'receive'})", "update.lua：台架和平台两个 OTA 入口都先删日志" },
                    new[] { u, "_G.ota_log_paused", "update.lua：OTA 进行中暂停写日志的开关" },
                    new[] { f, "if ota_paused() then return end", "fs_log.lua：OTA 进行中不缓存日志" },
                    new[] { f, "if ota_paused() then buf, buf_len = {}, 0; return true end", "fs_log.lua：OTA 进行中不写日志文件" },
                    // SAM | 2026-11-06 +08:00 | The temporary BLE location cache must go too, or COMPONENT_SPACE (75 KB seen on the bench).
                    new[] { u, "'/log/ble.ini'", "update.lua：OTA 发令前一并删除 /log/ble.ini（BLE 定位临时缓存）" },
                    new[] { u, "'[OTA_HOLD] '", "update.lua：OTA 保电锁，通知 GR 保持 CAT1 供电" },
                    new[] { u, "ota_hold(true)", "update.lua：OTA 命令一收到就上保电锁" },
                    new[] { u, "ota_hold(not stuck and (s.phase~='IDLE'", "update.lua：信标续锁，OTA 结束才放锁" } };
                int missingMust = 0;
                foreach (var m in must) if (!m[0].Contains(m[1])) { rep.Error("缺少 OTA 必检功能：" + m[2]); missingMust++; }
                if (missingMust == 0) rep.Ok("OTA 必检功能齐全：发令前清日志、OTA 中不写日志、保电锁（" + must.Length + " 项）");
            }
            if (rep.Errors.Count > 0) return null;

            rep.Log("[5] 编译与容量");
            string stage = Path.Combine(Path.GetTempPath(), "cat1_usb_import_" + Guid.NewGuid().ToString("N"));
            Directory.CreateDirectory(stage);
            try
            {
                foreach (var m in modules)
                {
                    string msg;
                    if (!Compile(Path.Combine(source, m + ".lua"), Path.Combine(stage, m + ".luac"), out msg)) rep.Error(m + ".lua 编译失败：" + msg);
                }
                foreach (var p in vendorFiles.Concat(assets)) File.Copy(p, Path.Combine(stage, Path.GetFileName(p)));
                var direct = Requires(main);
                var anchors = modules.Concat(vendorFiles.Select(Path.GetFileNameWithoutExtension)).Where(m => !direct.Contains(m)).OrderBy(x => x, StringComparer.Ordinal).ToList();
                var block = new List<string> { AnchorHead, "if false then" };
                block.AddRange(anchors.Select(m => "    require(\"" + m + "\")"));
                block.Add("end"); block.Add("");
                File.WriteAllBytes(Path.Combine(stage, "main.lua"), Utf8.GetBytes(string.Join("\r\n", block) + main));
                string check = Path.Combine(stage, "_main_check.luac"), cmsg;
                long mainLuac = 0;
                if (!Compile(Path.Combine(stage, "main.lua"), check, out cmsg)) rep.Error("main.lua（含锚点）编译失败：" + cmsg);
                else { mainLuac = new FileInfo(check).Length; File.Delete(check); }
                if (rep.Errors.Count > 0) return null;
                var sizes = Directory.GetFiles(stage).Where(p => Path.GetFileName(p) != "main.lua").ToDictionary(p => Path.GetFileName(p), p => new FileInfo(p).Length);
                sizes["main.luac"] = mainLuac;
                long total = LuaDbSize(sizes), spare = Capacity - total;
                if (spare < 0) rep.Error("LuaDB " + total + " 字节，超出 " + Capacity + " 字节 " + (-spare));
                else
                {
                    rep.Ok(sizes.Count + " 个文件，LuaDB " + total + "/" + Capacity + " 字节，余 " + spare + "（依赖锚点 " + anchors.Count + " 个）");
                    if (spare < 2048) rep.Warn("剩余空间不足 2 KiB（" + spare + " 字节）");
                    // SAM | 2026-11-04 +08:00 | Red line (budget.json): keep at least 16 KiB of the 512 KiB script area free.
                    string lv = Yp001.Budget.Level(total, Yp001.Budget.LuaDbYellow, Yp001.Budget.LuaDbRed);
                    string line = "脚本区红线 " + Yp001.Budget.LuaDbRed + "，离红线 " + (Yp001.Budget.LuaDbRed - total) + " 字节（" + Yp001.Budget.Source + "）";
                    if (lv == "red") rep.Error("超过" + line);
                    else if (lv == "yellow") rep.Warn("接近" + line + "：加功能前先删不用的模块");
                    else rep.Ok(line);
                }
                if (rep.Errors.Count > 0) return null;
                if (checkOnly) { rep.Log("仅检查，未输出文件。"); return null; }

                rep.Log("[6] 输出");
                var files = Directory.GetFiles(stage).OrderBy(x => Path.GetFileName(x), StringComparer.Ordinal).ToList();
                var hashes = new Dictionary<string, string>();
                foreach (var p in files) hashes[Path.GetFileName(p)] = Sha256(File.ReadAllBytes(p));
                var integrity = new Dictionary<string, object> {
                    { "tool", "Cat1UsbImport.exe" }, { "created", DateTime.Now.ToString("yyyy-MM-ddTHH:mm:ss") }, { "source", source },
                    { "version", fields }, { "luadb_bytes", total }, { "capacity", Capacity }, { "files", hashes } };
                string json = new JavaScriptSerializer().Serialize(integrity);
                var results = new List<string>();
                Directory.CreateDirectory(outDir);
                string target = Path.Combine(outDir, "USB_IMPORT");
                if (Directory.Exists(target) && Directory.EnumerateFileSystemEntries(target).Any())
                {
                    if (!force) { rep.Error(target + " 已存在且非空；要替换请加 --force，或换一个输出位置"); return null; }
                    if (!File.Exists(Path.Combine(target, "main.lua"))) { rep.Error(target + " 看起来不是 USB_IMPORT 目录（没有 main.lua），不覆盖"); return null; }
                    Directory.Delete(target, true);
                }
                Directory.CreateDirectory(target);
                foreach (var p in files) File.Copy(p, Path.Combine(target, Path.GetFileName(p)));
                var written = Directory.GetFiles(target).ToDictionary(p => Path.GetFileName(p), p => Sha256(File.ReadAllBytes(p)));
                if (written.Count != hashes.Count || hashes.Any(kv => !written.ContainsKey(kv.Key) || written[kv.Key] != kv.Value))
                { rep.Error("写出后回读的 sha256 与暂存不一致"); return null; }
                File.WriteAllText(Path.Combine(outDir, "integrity.json"), json, Utf8);
                rep.Ok("刷机目录：" + target + "（回读核对一致），记录：" + Path.Combine(outDir, "integrity.json"));
                results.Add(target);
                return results;
            }
            finally { try { Directory.Delete(stage, true); } catch { } }
        }
    }

