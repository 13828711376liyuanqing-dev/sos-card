        void Row(string label, TextBox box, ref int y)
        {
            Controls.Add(new Label { Text = label, Left = 12, Top = y + 4, Width = 230 });
            box.SetBounds(245, y, 625, 24); Controls.Add(box);
            var b = new Button { Text = "选择…", Left = 880, Top = y - 1, Width = 90 };
            b.Click += (s, e) => { using (var d = new FolderBrowserDialog { SelectedPath = box.Text }) if (d.ShowDialog() == DialogResult.OK) box.Text = d.SelectedPath; };
            Controls.Add(b); y += 32;
        }

        void Run()
        {
            log.Clear();
            if (src.Text.Trim() == "" || outp.Text.Trim() == "") { log.AppendText("请先选择源码目录和输出位置\r\n"); return; }
            string target = Path.Combine(outp.Text.Trim(), "USB_IMPORT");
            bool replace = false;
            if (Directory.Exists(target) && Directory.EnumerateFileSystemEntries(target).Any())
            {
                if (MessageBox.Show(this, "输出位置里已经有 USB_IMPORT：\r\n" + target + "\r\n\r\n要用这次的结果替换它吗？", "已有 USB_IMPORT", MessageBoxButtons.YesNo, MessageBoxIcon.Question) != DialogResult.Yes)
                { log.AppendText("已取消，没有生成\r\n"); return; }
                replace = true;
            }
            var rep = new Report(s => Put(Tone(s), s));
            try { Builder.Build(src.Text.Trim(), Builder.VendorFor(src.Text.Trim()), outp.Text.Trim(), false, replace, rep); }
            catch (Exception ex) { rep.Error("异常：" + ex.Message); }
            Put(Tone(rep.Summary()), rep.Summary());
        }

        // Deps colours: green = no impact, red = must be handled, null = normal
        // SAM | 2026-10-30 16:45 +08:00 | Failures red, warnings orange, a passed result green; plain lines stay black.
        static string Tone(string s)
        {
            string t = s.TrimStart();
            if (t.StartsWith("ERROR") || t.StartsWith("结果：失败")) return "red";
            if (t.StartsWith("WARN")) return "orange";
            if (t.StartsWith("结果：通过")) return "green";
            return null;
        }

        void Put(string color, string text)
        {
            log.SelectionStart = log.TextLength; log.SelectionLength = 0;
            log.SelectionColor = color == "green" ? Color.FromArgb(0, 128, 0) : color == "orange" ? Color.FromArgb(200, 110, 0) : color == "red" ? Color.Red : log.ForeColor;
            log.AppendText(text + "\r\n"); log.SelectionColor = log.ForeColor; Application.DoEvents();
        }

        void CheckDeps()
        {
            log.Clear();
            string dir = null;
            using (var d = new FolderBrowserDialog { Description = "选择已安装的 Luatools 文件夹（例如 D:\\Installers），用来对比版本。\r\n点“取消”则只检查工具包自带的文件。",
                SelectedPath = Directory.Exists(@"D:\Installers\_temp") ? @"D:\Installers" : "" })
                if (d.ShowDialog() == DialogResult.OK) dir = d.SelectedPath;
            int n = Deps.Report(Builder.ToolDir, "Cat1UsbImport", dir, x => Put(null, x), Put);
            Put(n == 0 ? "green" : "red", n == 0 ? "结果：通过" : "结果：有 " + n + " 项必须处理");
        }
    }

